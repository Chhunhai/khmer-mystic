#!/bin/sh
# Import the approved card artwork into the app.
#
#   sh scripts/import-card-art.sh ~/Downloads/Khmer-Mystic-Tarot
#
# Expects the art team's folders (Major_Arcana, Wands, Cups, Swords, Pentacles) with files
# named like 19-The-Sun.png or 01-Ace-of-Cups.png. Writes app-sized JPEGs to assets/cards/<card id>.jpg
# and regenerates src/ui/cardArt.ts. macOS only (uses sips).
set -eu

src=${1:?usage: sh scripts/import-card-art.sh <art folder>}
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/assets/cards"
map="$root/src/ui/cardArt.ts"
mkdir -p "$out"

for pair in Major_Arcana:MAJ Wands:WAN Cups:CUP Swords:SWO Pentacles:PEN; do
  folder=${pair%%:*}
  prefix=${pair##*:}
  for f in "$src/$folder"/[0-9][0-9]-*.png; do
    num=$(basename "$f" | cut -c1-2)
    # 480 × 720 covers the card's art window (about 120 pt wide) at 3× on phones; quality 72 keeps each file near 150 KB.
    sips -s format jpeg -s formatOptions 72 -Z 720 "$f" --out "$out/$prefix-$num.jpg" >/dev/null
  done
done

{
  echo '// Generated by scripts/import-card-art.sh. Do not edit by hand.'
  echo 'import type { ImageSourcePropType } from '"'"'react-native'"'"';'
  echo
  echo 'export const cardArt: Record<string, ImageSourcePropType> = {'
  for f in "$out"/*.jpg; do
    id=$(basename "$f" .jpg)
    echo "  '$id': require('../../assets/cards/$id.jpg'),"
  done
  echo '};'
} >"$map"

echo "$(ls "$out"/*.jpg | wc -l | tr -d ' ') images in assets/cards, $(du -sh "$out" | cut -f1) total"
