#!/bin/sh
# Import the 12 birth-year emblems into the app.
#
#   sh scripts/import-zodiac-emblems.sh ~/Downloads/Khmer-Zodiac-12-Animals
#
# Expects 12 PNGs named 01-Rat.png … 12-Pig-Wild-Boar.png, in the order of src/content/zodiac.json.
# Writes 288 px PNGs with the navy ground made transparent to assets/zodiac/<zodiac id>.png and
# regenerates src/ui/zodiacArt.ts. macOS only (uses sips).
set -eu

src=${1:?usage: sh scripts/import-zodiac-emblems.sh <emblem folder>}
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/assets/zodiac"
map="$root/src/ui/zodiacArt.ts"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$out"

ids="RAT OX TIG RAB DRA SNA HOR GOA MON ROO DOG PIG"
n=0
for id in $ids; do
  n=$((n + 1))
  num=$(printf '%02d' "$n")
  file=$(ls "$src"/"$num"-*.png | head -n 1)
  # 288 px covers the largest tile (108 pt on desktop, art at about 72%) at 3×.
  sips -s format png -Z 288 "$file" --out "$tmp/$id.png" >/dev/null
  python3 -I "$root/scripts/key-emblem.py" "$tmp/$id.png" "$out/$id.png"
done

{
  echo '// Generated by scripts/import-zodiac-emblems.sh. Do not edit by hand.'
  echo 'import type { ImageSourcePropType } from '"'"'react-native'"'"';'
  echo
  echo 'export const zodiacArt: Record<string, ImageSourcePropType> = {'
  for id in $ids; do
    echo "  $id: require('../../assets/zodiac/$id.png'),"
  done
  echo '};'
} >"$map"

echo "12 emblems in assets/zodiac, $(du -sh "$out" | cut -f1) total"
